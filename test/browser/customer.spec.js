import {test,expect} from '@playwright/test';
test('compte client mobile, photo panier et listes enregistrées',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.request.post('/api/session',{data:{code:'e2e-only-admin-code'}});
  const catalog=await (await page.request.get('/api/products')).json();
  const jpeg=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=40;c.height=40;return c.toDataURL('image/jpeg').split(',')[1]});
  const photo=await (await page.request.post('/api/photo',{data:Buffer.from(jpeg,'base64'),headers:{'Content-Type':'image/jpeg'}})).json();
  const product=await page.request.post('/api/products',{data:{name:'Pommes listes',family:catalog.categories[0].name,category:'',brand:'',origin:'France',purchasePrice:1,salePrice:2,stock:10,vat:5.5,saleType:'kilo',quantity:'1 kg',photo:photo.photo}});
  expect(product.ok(),await product.text()).toBeTruthy();
  const p=await product.json();
  await page.request.delete('/api/session');
  await page.reload();
  await page.locator(`[data-add="${p.id}"]`).click();
  await page.locator('#customer-toggle').click();
  await page.locator('#customer-form [name=name]').fill('Client test');
  await page.locator('#customer-form [name=email]').fill(`client-${Date.now()}@example.com`);
  await page.locator('#customer-form [name=password]').fill('test-customer-password-123');
  await page.getByRole('button',{name:'Créer mon compte',exact:true}).click();
  await expect(page.locator('#customer-space')).toBeVisible();
  await page.locator('#save-list [name=name]').fill('Mes courses du samedi');
  await page.getByRole('button',{name:'Enregistrer mon panier dans une liste'}).click();
  await expect(page.locator('#saved-lists')).toContainText('Mes courses du samedi');
  await page.reload();
  await page.locator('#customer-toggle').click();
  await expect(page.locator('#saved-lists')).toContainText('Mes courses du samedi');
  await page.getByRole('button',{name:'Ajouter au panier',exact:true}).click();
  await expect(page.locator('#customer-message')).toContainText('Liste ajoutée');
  await page.locator('#customer-dialog .close').click();
  await page.locator('#basket-toggle').click();
  await expect(page.locator('#cart-items img.cart-photo')).toBeVisible();
  await expect.poll(()=>page.locator('#cart-items img.cart-photo').evaluate(img=>img.naturalWidth)).toBeGreaterThan(0);
  await expect(page.locator('#cart-items input')).toHaveValue('2');
  await page.screenshot({path:'test-results/customer-cart.png',fullPage:true});
  await page.request.post('/api/session',{data:{code:'e2e-only-admin-code'}});
  const latest=await (await page.request.get('/api/products')).json();
  const removed=await page.request.delete('/api/products/'+p.id,{headers:{'If-Match':latest.revision}});
  expect(removed.ok()).toBeTruthy();
});
