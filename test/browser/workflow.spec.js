import { test, expect } from "@playwright/test";
test("gestion iPhone, photo, synchronisation ordinateur, commande et suppression", async ({
  browser,
}) => {
  const mobile = await browser.newContext({
    viewport: { width: 390, height: 844 },
    isMobile: true,
    hasTouch: true,
  });
  const admin = await mobile.newPage();
  const errors = [];
  admin.on("pageerror", (e) => errors.push(e.message));
  await admin.goto("/#gestion");
  await admin.getByLabel("Code administrateur").fill("e2e-only-admin-code");
  await admin
    .getByRole("button", { name: "Se connecter", exact: true })
    .click();
  await expect(
    admin.getByRole("button", { name: "+ Ajouter un produit" }),
  ).toBeVisible();
  await admin.getByRole("button", { name: "+ Ajouter un produit" }).click();
  await admin.getByLabel("Nom du produit").fill("Pommes test navigateur");
  await admin.getByLabel("Prix d’achat").fill("3");
  await admin.getByLabel("Prix de vente").fill("4");
  await admin.getByLabel("Stock (").fill("5");
  await admin.getByLabel("Poids / quantité").fill("1 kg");
  await admin.getByLabel("Type de vente").selectOption("kilo");
  await expect(admin.locator("#margin")).toContainText("inférieure à 30");
  // Real JPEG generated by browser, then passed through the same file import path as a phone.
  const jpeg = await admin.evaluate(() => {
    const c = document.createElement("canvas");
    c.width = 40;
    c.height = 40;
    c.getContext("2d").fillRect(0, 0, 40, 40);
    return c.toDataURL("image/jpeg").split(",")[1];
  });
  await admin
    .locator("#photo-input")
    .setInputFiles({
      name: "photo.jpg",
      mimeType: "image/jpeg",
      buffer: Buffer.from(jpeg, "base64"),
    });
  await expect(admin.locator("#photo-preview")).toBeVisible();
  await admin.getByRole("button", { name: "Enregistrer le produit" }).click();
  await expect(admin.locator("#product-dialog")).not.toBeVisible();
  await expect(admin.locator("#admin-products")).toContainText(
    "Pommes test navigateur",
  );
  const desktop = await browser.newContext({
    viewport: { width: 1280, height: 900 },
  });
  const shop = await desktop.newPage();
  shop.on("pageerror", (e) => errors.push(e.message));
  await shop.goto("/");
  await expect(shop.locator("#products")).toContainText(
    "Pommes test navigateur",
  );
  await expect(shop.locator("#products")).not.toContainText("Achat HT");
  await expect(shop.locator("#products img")).toBeVisible();
  expect(
    await shop
      .locator("#products img")
      .evaluate((i) => i.complete && i.naturalWidth > 0),
  ).toBe(true);
  expect(
    await shop
      .locator("#products")
      .evaluate(
        (e) => getComputedStyle(e).gridTemplateColumns.split(" ").length,
      ),
  ).toBe(3);
  await admin.getByRole("button", { name: "Modifier", exact: true }).click();
  await admin.getByLabel("Prix d’achat").fill("3.2");
  await admin.getByLabel("Prix de vente").fill("5");
  await admin.getByRole("button", { name: "Enregistrer le produit" }).click();
  await expect(admin.locator("#product-dialog")).not.toBeVisible();
  await expect(shop.locator("#products .price")).toContainText("5,00", {
    timeout: 15000,
  });
  await shop.getByRole("button", { name: "+ Ajouter", exact: true }).click();
  await shop.locator("#basket-toggle").click();
  await shop.getByLabel("Nom et prénom").fill("Client Test");
  await shop.getByLabel("Téléphone", { exact: true }).fill("0600000000");
  await shop.getByLabel("Email", { exact: true }).fill("test@example.com");
  await shop.locator("#pickup").selectOption({ index: 1 });
  await shop.getByRole("button", { name: "Confirmer ma commande" }).click();
  await expect(shop.locator("#confirmation")).toContainText(
    "Votre commande est enregistrée",
  );
  await admin.getByRole("button", { name: "Actualiser", exact: true }).click();
  await expect(admin.locator("#orders")).toContainText("Client Test");
  await expect(admin.locator("#admin-products")).toContainText("4 en stock");
  await admin.locator("[data-order]").selectOption("prête");
  await expect(admin.locator("[data-order]")).toHaveValue("prête");
  await expect(admin.locator("#notice")).toContainText("État enregistré");
  expect(
    await admin.evaluate(
      () => document.documentElement.scrollWidth <= innerWidth,
    ),
  ).toBe(true);
  await admin.screenshot({
    path: "test-results/gestion-iphone.png",
    fullPage: true,
  });
  await shop.locator('[data-close="cart-dialog"]').click();
  await shop.screenshot({
    path: "test-results/boutique-desktop.png",
    fullPage: true,
  });
  admin.once("dialog", (d) => d.accept());
  await admin.getByRole("button", { name: "Supprimer", exact: true }).click();
  await expect(admin.locator("#admin-products")).not.toContainText(
    "Pommes test navigateur",
  );
  await expect(shop.locator("#products")).not.toContainText(
    "Pommes test navigateur",
    { timeout: 15000 },
  );
  const phoneShop = await mobile.newPage();
  await phoneShop.goto("/");
  await expect(phoneShop.locator("#products")).toContainText(
    "Le marché prépare ses rayons",
  );
  expect(
    await phoneShop.evaluate(
      () => document.documentElement.scrollWidth <= innerWidth,
    ),
  ).toBe(true);
  expect(errors).toEqual([]);
  await mobile.close();
  await desktop.close();
});
